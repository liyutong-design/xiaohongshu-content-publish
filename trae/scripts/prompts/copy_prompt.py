# 输出格式约束（工程化补充）：完整笔记 = 标题 + 正文 + 话题标签
COPY_OUTPUT_INSTRUCTION = """## 输出格式（必须严格遵守）
仅输出一个 JSON 对象，不要输出任何其他解释，不要使用 ``` 代码块：
{
  "domain": "识别出的内容领域（美妆/穿搭/美食/旅行/养生/校园/电商/作品展示/日常分享/教程/其他）",
  "note_title": "完整笔记标题（含emoji，15-20字内）",
  "note_body": "完整发布正文（按黄金结构组织，用emoji自然分段，不含换行符之外的额外说明）",
  "hashtags": ["话题标签1", "话题标签2", "...(共5-10个，不含#号)"]
}"""


def build_copy_user_prompt(topic: str, author: str, options: dict = None) -> str:
    """构造用户提示词。topic 对应 Coze 开始节点的 kw，author 对应 zhanghao。"""
    options = options or {}
    lines = [f"用户输入关键词/原始内容：{topic}"]
    if author:
        lines.append(f"作者/账号署名：{author}")
    for key, label in (
        ("audience", "目标人群"), ("tone", "语气要求"),
        ("visual_style", "视觉风格"), ("key_points", "必须体现的重点"),
        ("avoid", "禁止出现的内容"),
    ):
        value = options.get(key)
        if value:
            lines.append(f"{label}：{value}")
    return "\n".join(lines)

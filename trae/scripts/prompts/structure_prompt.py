def build_structure_user_prompt(note: dict, author: str) -> str:
    """note 来自 generate_copy 的输出：note_title / note_body / hashtags / domain。"""
    tags = " ".join("#" + t for t in note.get("hashtags", []))
    return (
        f"内容领域：{note.get('domain', '未识别')}\n"
        f"作者名：{author}\n"
        f"笔记标题：{note.get('note_title', '')}\n"
        f"笔记正文：{note.get('note_body', '')}\n"
        f"话题标签：{tags}"
    )
